"""Markdown back-testing report."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def _md(df: pd.DataFrame, floatfmt: str = ".3f", index: bool = True) -> str:
    df = df.reset_index() if index else df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else format(v, floatfmt))
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def write_report(path: Path, ctx: dict) -> Path:
    lines = [
        "# VaR / ES back-testing report",
        "",
        f"*Data: **{ctx['source']}**, {ctx['assets']}. Out-of-sample period "
        f"{ctx['start']} to {ctx['end']} ({ctx['n_days']:,} days), rolling "
        f"{ctx['window']}-day estimation window, GARCH re-estimated every "
        f"{ctx['refit_every']} days.*",
        "",
        "Generated by `scripts/run_backtest.py`. Do not edit by hand.",
        "",
        "![Portfolio](figures/portfolio.png)",
        "",
        "## 1. Regulatory back-tests (1-day VaR 99%, ES 97.5%)",
        "",
        "Kupiec tests the exception rate, Christoffersen tests clustering (independence "
        "and conditional coverage), the traffic light counts exceptions over 250 days, and "
        "Z2 is the Acerbi-Szekely ES test (green < 0.70, red > 1.80).",
        "",
        _md(ctx["summary"]),
        "",
        "![Traffic light](figures/traffic_light.png)",
        "",
        "## 2. Behaviour in stress periods (exception rate %, expected 1%)",
        "",
        _md(ctx["periods"], ".2f"),
        "",
        "![GFC](figures/var_gfc.png)",
        "![COVID](figures/var_covid.png)",
        "",
        "## 3. Model ranking (consistent scoring functions)",
        "",
        "FZ0 is the Fissler-Ziegel loss for the pair (VaR, ES) at 97.5%; the quantile loss "
        "scores VaR 99%. The Diebold-Mariano test (Newey-West variance) compares each model "
        "with the best one.",
        "",
        _md(ctx["ranking"], ".4f"),
        "",
        "![Ranking](figures/ranking.png)",
        "",
        "Pairwise DM statistics on FZ0 loss (negative = row model better than column):",
        "",
        _md(ctx["dm_matrix"], ".1f"),
        "",
        "## 4. Square-root-of-time rule (10-day VaR 99% = sqrt(10) x 1-day)",
        "",
        _md(ctx["ten_day"], ".3f"),
        "",
        "![Full period](figures/var_full.png)",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return path
